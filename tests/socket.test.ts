import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { test } from 'node:test';
import { setTimeout as delay } from 'node:timers/promises';
import { Server } from 'socket.io';
import { io, type Socket } from 'socket.io-client';
import type { Ack, ClientEvents, PlayerSession, RoomView, ServerEvents } from '../shared/types';
import { RoomStore } from '../server/rooms';
import { attachGameSockets, broadcastRoom, type GameServer } from '../server/socket';

test('real Socket.IO clients complete a synchronized round, reconnect, score, and reset', async (context) => {
  const http = createServer();
  const server: GameServer = new Server(http);
  const store = new RoomStore((code) => broadcastRoom(server, store, code), { answer: 5000, bluff: 5000, debate: 40, vote: 5000 });
  attachGameSockets(server, store);
  await new Promise<void>((resolve) => http.listen(0, '127.0.0.1', resolve));
  const address = http.address();
  assert.ok(address && typeof address === 'object');
  const url = `http://127.0.0.1:${address.port}`;
  const clients: Socket<ServerEvents, ClientEvents>[] = [];
  context.after(async () => { clients.forEach((socket) => socket.disconnect()); store.close(); await new Promise<void>((resolve) => server.close(() => resolve())); });
  const connect = async () => {
    const socket: Socket<ServerEvents, ClientEvents> = io(url, { forceNew: true, transports: ['websocket'] });
    clients.push(socket);
    await new Promise<void>((resolve, reject) => { socket.once('connect', resolve); socket.once('connect_error', reject); });
    return socket;
  };
  const host = await connect();
  const guest = await connect();
  let hostView: RoomView | undefined;
  let guestView: RoomView | undefined;
  host.on('room:state', (view) => { hostView = view; });
  guest.on('room:state', (view) => { guestView = view; });
  const create = await new Promise<Ack<PlayerSession>>((resolve) => host.emit('room:create', { name: 'Suriya' }, resolve));
  assert.ok(create.ok);
  const join = await new Promise<Ack<PlayerSession>>((resolve) => guest.emit('room:join', { roomCode: create.data.roomCode, name: 'Perry' }, resolve));
  assert.ok(join.ok);
  await delay(10);
  assert.equal(hostView?.players.length, 2);
  assert.equal(guestView?.players.length, 2);
  const blockedSetup = await new Promise<Ack>((resolve) => guest.emit('game:questions', { mode: 'single', selectedPackIds: ['builtin-easy-geography'] }, resolve));
  assert.equal(blockedSetup.ok, false);
  const setup = await new Promise<Ack>((resolve) => host.emit('game:questions', { mode: 'single', selectedPackIds: ['builtin-easy-science-nature'] }, resolve));
  assert.ok(setup.ok);
  await delay(10);
  assert.deepEqual(hostView?.selectedPackIds, ['builtin-easy-science-nature']);
  assert.deepEqual(guestView?.selectedPackIds, ['builtin-easy-science-nature']);
  const unauthorized = await new Promise<Ack>((resolve) => guest.emit('game:start', resolve));
  assert.equal(unauthorized.ok, false);
  const start = await new Promise<Ack>((resolve) => host.emit('game:start', resolve));
  assert.ok(start.ok);
  store.getRoom(create.data.roomCode).totalRounds = 1;
  const correct = store.getRoom(create.data.roomCode).question!.correctAnswer;
  await new Promise<Ack>((resolve) => host.emit('answer:submit', { answer: correct }, resolve));
  await delay(10);
  assert.equal(guestView?.me.genuineAnswer, null);
  assert.equal(JSON.stringify(guestView).includes(correct), false);
  guest.disconnect();
  const reconnected = await connect();
  reconnected.on('room:state', (view) => { guestView = view; });
  const restore = await new Promise<Ack<PlayerSession>>((resolve) => reconnected.emit('room:reconnect', join.data, resolve));
  assert.ok(restore.ok);
  await new Promise<Ack>((resolve) => reconnected.emit('answer:submit', { answer: 'Canada' }, resolve));
  await new Promise<Ack>((resolve) => host.emit('bluff:submit', { answer: 'Norway' }, resolve));
  await new Promise<Ack>((resolve) => reconnected.emit('bluff:submit', { answer: 'Canada' }, resolve));
  await delay(70);
  assert.equal(hostView?.phase, 'vote');
  assert.equal(guestView?.phase, 'vote');
  assert.deepEqual(hostView?.answerPool, guestView?.answerPool);
  assert.equal(hostView?.answerPool.some((answer) => answer.isCorrect !== undefined || answer.bluffPlayerIds), false);
  const sweden = hostView!.answerPool.find((answer) => answer.text === correct)!;
  const norway = hostView!.answerPool.find((answer) => answer.text === 'Norway')!;
  await new Promise<Ack>((resolve) => host.emit('vote:submit', { answerId: sweden.id, hill: true }, resolve));
  await delay(10);
  assert.equal(guestView?.hillPlayerIds.includes(create.data.playerId), true);
  assert.equal(guestView?.me.vote, null);
  await new Promise<Ack>((resolve) => reconnected.emit('vote:submit', { answerId: norway.id, hill: true }, resolve));
  for (let step = 0; step < 4; step++) await new Promise<Ack>((resolve) => host.emit('reveal:continue', resolve));
  await delay(10);
  assert.equal(hostView?.phase, 'results');
  assert.equal(guestView?.phase, 'results');
  const winner = hostView!.results.find((result) => result.playerId === create.data.playerId)!;
  assert.equal(winner.finalAnswerPoints, 100);
  assert.equal(winner.bluffPoints, 100);
  assert.equal(winner.totalScore, 300, 'Hill does not double bluff points');
  const loser = guestView!.results.find((result) => result.playerId === join.data.playerId)!;
  assert.equal(loser.totalScore, -100);
  const final = await new Promise<Ack>((resolve) => host.emit('game:advance', resolve));
  assert.ok(final.ok);
  const reset = await new Promise<Ack>((resolve) => host.emit('game:reset', resolve));
  assert.ok(reset.ok);
  await delay(10);
  assert.equal(hostView?.phase, 'lobby');
  assert.equal(guestView?.phase, 'lobby');
  assert.equal(guestView?.players.every((player) => player.score === 0 && !player.hillUsed), true);
  assert.deepEqual(guestView?.selectedPackIds, ['builtin-easy-science-nature'], 'Play Again retains question setup');
});
